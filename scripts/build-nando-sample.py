#!/usr/bin/env python3
"""Turn a NANDO notified-body list export into RDF the way the Organisation
Codes Register (OCR-KG) models organisations, and report how that list lines
up with what ERA already holds.

NANDO has no open data: the CSV is what the list page's download button gives
(here: legislationId 31, active notifications only). It carries the NB number
but not NANDO's own reference code (NANDO_INPUT_nnnnnn), so it cannot be joined
to a NANDO body-version page.

Matching, per NANDO body:
  - ERADIS: by NB number, against the organisations in the ERADIS snapshot
    (era:role/era:nandoCode holds "NB nnnn").
  - OCR-KG: OCR has no NB numbers, so by name (or short name) within the
    country, and by website domain. Name similarity >= 0.9, or >= 0.75 with
    the same website, is "confirmed". The same website with a weaker name is
    "uncertain": one domain often covers several legal entities of a group
    (Bureau Veritas, TÜV SÜD). Below 0.9 a name alone is not enough - at 0.75
    it paired TÜV SÜD Nederland with VIAS Nederland and RINA Services with
    Agriservice (checked by hand, 2026-10-30).

Usage:  python3 scripts/build-nando-sample.py [--endpoint URL]
Writes: eradis/nando-sample-data/nando-active-nobos-leg31.ttl
        eradis/nando-sample-data/nando-ocr-eradis-match.csv
"""
import argparse, csv, difflib, gzip, json, pathlib, re, unicodedata, urllib.parse, urllib.request

ROOT = pathlib.Path(__file__).resolve().parent.parent
DIR = ROOT / "eradis" / "nando-sample-data"
SNAPSHOT = ROOT / "scripts" / "assets" / "era-eradis-snapshot.json.gz"

ISO3 = {"Austria": "AUT", "Belgium": "BEL", "Bulgaria": "BGR", "Croatia": "HRV", "Czech Republic": "CZE",
        "Denmark": "DNK", "Finland": "FIN", "France": "FRA", "Germany": "DEU", "Greece": "GRC", "Hungary": "HUN",
        "Italy": "ITA", "Latvia": "LVA", "Luxembourg": "LUX", "Netherlands": "NLD", "Norway": "NOR",
        "Poland": "POL", "Portugal": "PRT", "Romania": "ROU", "Slovakia": "SVK", "Slovenia": "SVN",
        "Spain": "ESP", "Switzerland": "CHE"}

LEGAL = (r"\b(s\.?r\.?l\.?u?|s\.?p\.?a|s\.?a|s\.?l|slu|b\.?v|gmbh|ag|aps|as|oy|ltd|sp\.? ?z\.? ?o\.? ?o|d\.?o\.?o|"
         r"a\.?s|zrt|kft|s\.?a\.?r\.?l|mbh|unipersonal|spolka z ograniczona odpowiedzialnoscia|"
         r"korlatolt felelossegu tarsasag|nonprofit)\b")


def norm(s):
    # Ł/ł has no decomposition: without this "SPÓŁKA" survives as "spoka"
    s = unicodedata.normalize("NFKD", (s or "").replace("Ł", "L").replace("ł", "l")).encode("ascii", "ignore").decode().lower()
    s = re.sub(LEGAL, " ", s)
    return " ".join(re.sub(r"[^a-z0-9 ]", " ", s).split())


def domain(u):
    if not u:
        return ""
    host = urllib.parse.urlparse(u.strip() if "://" in u else "http://" + u.strip()).netloc.lower()
    return host[4:] if host.startswith("www.") else host


def ocr_organisations(endpoint):
    query = (DIR / "ocr-organisations.rq").read_text(encoding="utf-8")
    req = urllib.request.Request(endpoint, data=urllib.parse.urlencode({"query": query}).encode(),
                                 headers={"Accept": "application/sparql-results+json"})
    rows = json.load(urllib.request.urlopen(req, timeout=120))["results"]["bindings"]
    v = lambda r, k: r.get(k, {}).get("value", "")
    return [dict(iri=v(r, "org"), code=v(r, "code"), name=v(r, "name"),
                 nicks=[n for n in v(r, "nicks").split("|") if n], cc=v(r, "country").rsplit("/", 1)[-1],
                 roles=[x for x in v(r, "roles").split("|") if x], dom=domain(v(r, "web"))) for r in rows]


def match(body, ocr):
    cc, name, dom = ISO3[body["Country"]], norm(body["Name"]), domain(body["Website"])
    best = (0.0, False, None)
    for o in ocr:
        if o["cc"] != cc:
            continue
        ratio = max(difflib.SequenceMatcher(None, name, norm(x)).ratio() for x in [o["name"], *o["nicks"]])
        same_dom = bool(dom and o["dom"] and dom == o["dom"])
        if (ratio, same_dom) > best[:2]:
            best = (ratio, same_dom, o)
    ratio, same_dom, o = best
    if ratio >= 0.9 or (same_dom and ratio >= 0.75):
        return "confirmed", o, ratio
    if same_dom:
        return "uncertain", o, ratio
    return "none", None, ratio


def lit(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def turtle(rows):
    nando = "https://example.org/nando/"
    era = "http://data.europa.eu/949/"
    out = [f"""# Notified bodies with an active notification under NANDO legislationId 31,
# from body.csv (the NANDO list export), modelled the OCR-KG way.
# Generated by scripts/build-nando-sample.py - do not edit by hand.
#
# A body ERA already knows (confirmed OCR-KG match) keeps its OCR IRI, and so
# does its NOBO role; the others get a placeholder IRI under {nando} until ERA
# allocates a code. Site, address and homepage always get NANDO IRIs, so that
# NANDO's address never merges into OCR-KG's own address resource.
# era:nandoCode sits on the NOBO role, as in ERADIS (domain era:OrganisationRole).
# Phone, fax and e-mail are left out: OCR-KG publishes none, and several
# NANDO e-mails name a person.
# nando:Notification and nando:legislation/31 are proposed terms, not ERA ones;
# which act legislationId 31 is has not been confirmed.

@prefix era:   <{era}> .
@prefix org:   <http://www.w3.org/ns/org#> .
@prefix locn:  <http://www.w3.org/ns/locn#> .
@prefix foaf:  <http://xmlns.com/foaf/0.1/> .
@prefix dct:   <http://purl.org/dc/terms/> .
@prefix rdfs:  <http://www.w3.org/2000/01/rdf-schema#> .
@prefix skos:  <http://www.w3.org/2004/02/skos/core#> .
@prefix nando: <{nando}> .

<{nando}legislation/31> a skos:Concept ;
    skos:notation "31" ;
    skos:prefLabel "NANDO legislation 31"@en ;
    rdfs:seeAlso <https://webgate.ec.europa.eu/single-market-compliance-space/notified-bodies/notified-body-list?filter=legislationId:31,notificationStatusId:1> .
"""]
    for r in rows:
        num = r["nb"].split()[-1]
        known = r["ocr_status"] == "confirmed"
        body = f"{era}body/organisation/{r['ocr_code']}" if known else f"{nando}body/NB{num}"
        role = (f"{era}body/organisation/organisationRole/{r['ocr_code']}_NOBO" if known
                else f"{nando}body/organisationRole/NB{num}_NOBO")
        site, addr, doc = (f"{nando}body/{kind}/NB{num}" for kind in ("site", "address", "document"))
        cc = f"http://publications.europa.eu/resource/authority/country/{r['cc']}"
        full = "\n".join(x for x in (r["address"], r["city"], r["country"]) if x)
        b = [f"<{body}> a era:Body , org:Organization ;",
             f"    foaf:name {lit(r['name'])} ;",
             f"    org:hasSite <{site}> ;",
             f"    era:role <{role}>"]
        if known:
            b.insert(1, f"    era:organisationCode {lit(r['ocr_code'])} ;")
        if r["web"]:
            b[-1] += " ;"
            b.append(f"    foaf:homepage <{doc}>")
        if r["ocr_status"] == "uncertain":
            b[-1] += " ;"
            b.append(f"    rdfs:seeAlso <{era}body/organisation/{r['ocr_code']}> ;")
            b.append(f"    rdfs:comment {lit('Same website as OCR body ' + r['ocr_code'] + ' (' + r['ocr_name'] + '); not confirmed to be the same legal entity.')}@en")
        out.append("\n".join(b) + " .")
        out.append(f"""<{role}> a era:OrganisationRole ;
    era:hasOrganisationRole <{era}concepts/organisation-roles/NOBO> ;
    era:roleOf <{body}> ;
    era:nandoCode {lit(r['nb'])} ;
    nando:hasNotification [ a nando:Notification ;
        dct:subject <{nando}legislation/31> ;
        nando:notificationStatus <{nando}notification-statuses/1> ] .""")
        out.append(f"""<{site}> a org:Site ;
    rdfs:label {lit('Site of ' + r['name'])}@en ;
    org:siteAddress <{addr}> .
<{addr}> a locn:Address ;
    locn:thoroughfare {lit(r['address'])} ;
    locn:postName {lit(r['city'])} ;
    locn:adminUnitL1 <{cc}> ;
    locn:fullAddress {lit(full)} .""")
        if r["web"]:
            url = r["web"] if "://" in r["web"] else "http://" + r["web"]
            out.append(f"""<{doc}> a era:Document ;
    foaf:page <{url.replace(' ', '')}> ;
    foaf:primaryTopic <{body}> .""")
        out.append("")
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--endpoint", default="https://graph.data.era.europa.eu/repositories/OCR-KG")
    args = ap.parse_args()

    bodies = list(csv.DictReader(open(DIR / "body.csv", encoding="utf-8")))
    ocr = ocr_organisations(args.endpoint)
    eradis = {}
    for name, cc, reg, nb, key in json.load(gzip.open(SNAPSHOT))["orgs"]:
        if nb:
            eradis.setdefault(nb, []).append(name)

    rows = []
    for b in bodies:
        status, o, ratio = match(b, ocr)
        rows.append(dict(nb=b["Body type"], name=b["Name"].strip(), cc=ISO3[b["Country"]], country=b["Country"],
                         address=b["Address"].strip(), city=b["City"].strip(), web=b["Website"].strip(),
                         ocr_status=status, ocr_code=o["code"] if o else "", ocr_name=o["name"] if o else "",
                         ocr_roles="|".join(o["roles"]) if o else "",
                         ocr_has_nobo="NOBO" in o["roles"] if o and status == "confirmed" else False,
                         name_similarity=round(ratio, 2), in_eradis=bool(eradis.get(b["Body type"])),
                         eradis_names=" | ".join(sorted(set(eradis.get(b["Body type"], []))))))

    cols = ["nb", "name", "cc", "ocr_status", "ocr_code", "ocr_name", "ocr_roles", "ocr_has_nobo",
            "name_similarity", "in_eradis", "eradis_names"]
    with open(DIR / "nando-ocr-eradis-match.csv", "w", encoding="utf-8", newline="") as f:
        w = csv.DictWriter(f, fieldnames=cols, extrasaction="ignore")
        w.writeheader()
        w.writerows(sorted(rows, key=lambda r: (r["cc"], r["nb"])))
    (DIR / "nando-active-nobos-leg31.ttl").write_text(turtle(rows), encoding="utf-8")

    active = {r["nb"] for r in rows}
    confirmed = {r["ocr_code"] for r in rows if r["ocr_status"] == "confirmed"}
    count = lambda f: sum(1 for r in rows if f(r))
    print(f"NANDO bodies: {len(rows)}")
    print(f"  in ERADIS by NB number: {count(lambda r: r['in_eradis'])}")
    print(f"  OCR-KG confirmed: {count(lambda r: r['ocr_status'] == 'confirmed')}"
          f" (with NOBO role {count(lambda r: r['ocr_has_nobo'])}), uncertain: {count(lambda r: r['ocr_status'] == 'uncertain')}")
    print("  not in ERADIS:", sorted(r["nb"] for r in rows if not r["in_eradis"]))
    print("ERADIS NB numbers not on the active list:",
          {nb: sorted(set(n))[0] for nb, n in sorted(eradis.items()) if nb not in active})
    print("OCR NOBO bodies not on the active list:",
          [(o["code"], o["name"]) for o in ocr if "NOBO" in o["roles"] and o["code"] not in confirmed])


if __name__ == "__main__":
    main()
